; Procedure: draw_sprite
; Phase / Module: Phase 2 - Module 4 (Sprites)
; Purpose: Renders a 16-pixel-wide bitmap sprite with transparency (color 0),
;          4-edge screen clipping, and optional horizontal mirror flip.
; Inputs: [bp+12]=x, [bp+10]=y, [bp+8]=height, [bp+6]=sprite_ptr, [bp+4]=flip
; Outputs: Draws sprite pixels into buffer_seg
; Registers Changed: No


draw_sprite:
    push bp
    mov bp, sp
    push ax
    push bx
    push cx
    push dx
    push si
    push di
    push es

    mov es, [buffer_seg]
    mov si, [bp+6]
    xor cx, cx

.spr_row:
    cmp cx, [bp+8]
    jge .spr_done

    mov ax, [bp+10]
    add ax, cx
    cmp ax, 0
    jl .spr_next_row
    cmp ax, SCREEN_H
    jge .spr_done

    mov di, ax
    shl di, 8
    shl ax, 6
    add di, ax

    xor bx, bx

.spr_col:
    cmp bx, 16
    jge .spr_next_row

    cmp byte [bp+4], 0
    je .no_flip
    mov ax, 15
    sub ax, bx
    push bx
    mov bx, ax
    mov al, [si + bx]
    pop bx
    jmp .check_trans

.no_flip:
    mov al, [si + bx]

.check_trans:
    cmp al, COL_TRANSPARENT
    je .spr_next_col

    mov dx, [bp+12]
    add dx, bx
    cmp dx, 0
    jl .spr_next_col
    cmp dx, SCREEN_W
    jge .spr_next_col

    push bx
    mov bx, dx
    mov [es:di + bx], al
    pop bx

.spr_next_col:
    inc bx
    jmp .spr_col

.spr_next_row:
    add si, 16
    inc cx
    jmp .spr_row

.spr_done:
    pop es
    pop di
    pop si
    pop dx
    pop cx
    pop bx
    pop ax
    pop bp
    ret 10